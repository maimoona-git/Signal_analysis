"""Writes app/gui/viridis_table.inc: the 256-entry RGB lookup table of pyqtgraph's
"viridis" colormap, which is what the native app's waterfall uses, so the C++
waterfall colours the same way. Dev-time only:

    ~/signal-project/signal/.venv/bin/python ml/make_viridis_table.py
"""

from pathlib import Path

import pyqtgraph as pg

OUT = Path(__file__).resolve().parent.parent / "app" / "gui" / "viridis_table.inc"

lut = pg.colormap.get("viridis").getLookupTable(nPts=256, alpha=False)
assert lut.shape == (256, 3)
rows = [f"    {{{r}, {g}, {b}}}," for r, g, b in lut.tolist()]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("// Generated by ml/make_viridis_table.py from pyqtgraph's viridis colormap. Do not edit.\n"
               + "\n".join(rows) + "\n")
print(f"wrote {OUT} (first {lut[0].tolist()}, last {lut[255].tolist()})")
